# 4. OPERATORS IN PYTHON


# Arithmetic Operators 
a = 3
b = 8
c = a + b 
print (c)

# Assignment Operators
a = 4-2 # Assign 4-2 in a
print(a)
b = 6 
b += 3 # increment the value of b by 3 and then assign it to b
print(b)

# Comparison Operators
d = 5<4
print(d)
c = 5>4
print(c)

a = 5!=4
print (a)

# != means not equal to
# == means double equal to. If 5 == 5 means kya 5, 5 ke barabar hain, so answer is yes

# Logical Operators
e = 1 or 2 
print(e)
c = True or False
print(c)

# Truth table of 'or'
print("True or false is", True or False) # True
print("True or True is" , True or True) # True
print("False or False is" , False or True) # True
print("False or False is" , False or False) # False

# Truth table of and
print("True and false is", True and False) # False
print("True and True is" , True and True) # True
print("False and False is" , False and True) #False
print("False and False is" , False and False) # False

# not
print(not(True))
print(not(False))