# 5. ESCAPE SEQUENCE CHARACTERS

# \n # ye line ko niche le jata hain
a = "komal is a good girl\nbut not a bad\ngirl"

print(a)

# \t # ye tab jitna space deta hain
a = "Komal ia a good girl\tbut not a bad girl"

print(a)

# \"...\" 
a = "Komal is a good \"girl\" but not a bad \"girl\""

print(a)

# \\
a = "Komal is a good girl\\but not a bad girl"

print(a)

# \r — Carriage Return

print("Hello\rWorld")

# \b

print("ABC\bD")

# \a - Alert \ Bell

print("\a")

print("Warning!\a")